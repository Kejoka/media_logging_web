-- Repair the media type constraint on notification tables created before Music.
do $$
declare
  constraint_name text;
begin
  for constraint_name in
    select pg_constraint.conname
    from pg_constraint
    join pg_class on pg_class.oid = pg_constraint.conrelid
    join pg_namespace on pg_namespace.oid = pg_class.relnamespace
    where pg_namespace.nspname = 'public'
      and pg_class.relname = 'user_activities'
      and pg_constraint.contype = 'c'
      and pg_get_constraintdef(pg_constraint.oid) like '%media_type%'
  loop
    execute format('alter table public.user_activities drop constraint %I', constraint_name);
  end loop;

  alter table public.user_activities
    add constraint user_activities_media_type_check
    check (media_type in ('games', 'movies', 'shows', 'books', 'music'));
end;
$$;

