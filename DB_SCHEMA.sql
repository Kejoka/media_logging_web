-- Create user challenges (year + medium specific goals)
create table
  user_challenges (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users on delete cascade,
    medium text not null,
    year int not null,
    challenge_type text not null check (challenge_type in ('count', 'pages', 'completion')),
    label text not null,
    target_count int not null check (target_count > 0),
    created_at timestamp with time zone default now(),
    updated_at timestamp with time zone default now(),
    unique (user_id, medium, year, challenge_type)
  );

alter table user_challenges enable row level security;

create policy "Users can view all challenges." on user_challenges
  for select using (true);

create policy "Users can insert own challenges." on user_challenges
  for insert with check ((select auth.uid()) = user_id);

create policy "Users can update own challenges." on user_challenges
  for update using ((select auth.uid()) = user_id);

create policy "Users can delete own challenges." on user_challenges
  for delete using ((select auth.uid()) = user_id);

-- Stored procedure for upserting preferences
CREATE OR REPLACE FUNCTION upsert_and_change_factor(r_user_preference_id bigint, r_tmdb_id bigint, r_name varchar(50), r_factor real) RETURNS VOID AS $$
BEGIN
    INSERT INTO preferences (user_preference_id, tmdb_id, name, factor)
    VALUES (r_user_preference_id, r_tmdb_id, r_name, r_factor)
    ON CONFLICT (user_preference_id, tmdb_id)
    DO UPDATE SET factor = preferences.factor + r_factor;
END;
$$ LANGUAGE plpgsql;
