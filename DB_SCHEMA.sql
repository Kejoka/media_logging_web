-- Existing profiles keep their selected media types as a comma-separated list.
-- Enable the new type for existing users while preserving all previous choices.
update profiles
set enabled_media_types = concat_ws(',', nullif(enabled_media_types, ''), 'music')
where not exists (
  select 1
  from unnest(string_to_array(coalesce(enabled_media_types, ''), ',')) as media_type
  where btrim(media_type) = 'music'
);

